/** Roue dentée générée géométriquement (8 dents). */
function gearPath(teeth = 8, rOut = 9.4, rIn = 7.1, halfOut = 8, halfIn = 13): string {
  const pts: string[] = [];
  const step = 360 / teeth;
  const at = (radius: number, deg: number) => {
    const a = ((deg - 90) * Math.PI) / 180;
    return `${(12 + radius * Math.cos(a)).toFixed(2)} ${(12 + radius * Math.sin(a)).toFixed(2)}`;
  };
  for (let i = 0; i < teeth; i++) {
    const mid = i * step;
    pts.push(at(rIn, mid - halfIn), at(rOut, mid - halfOut), at(rOut, mid + halfOut), at(rIn, mid + halfIn));
  }
  return `M${pts.join('L')}Z`;
}

/** Hélice à trois pales (ventilateur). */
function fanPath(): string {
  const parts: string[] = [];
  for (let i = 0; i < 3; i++) {
    const a = ((i * 120 - 90) * Math.PI) / 180;
    const P = (x: number, y: number) => `${(12 + x * Math.cos(a) - y * Math.sin(a)).toFixed(2)} ${(12 + x * Math.sin(a) + y * Math.cos(a)).toFixed(2)}`;
    parts.push(`M${P(2.2, 0)}C${P(3.6, 4)} ${P(9, 3.4)} ${P(9, 0.3)}C${P(9, -2)} ${P(5.2, -1.7)} ${P(2.2, 0)}Z`);
  }
  return parts.join('');
}

