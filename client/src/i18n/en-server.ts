/** Définition d'un flux vidéo dans un message du serveur (« 1920 × 1080 (H.264) », « définition inconnue »). */
const resolution = (s: string) => s.replace('définition inconnue', 'unknown resolution');

/**
 * Messages qui contiennent un nombre ou un nom : modèle du texte français → traduction, texte avec $1, $2… (parties
 * gardées) ou fonction qui reçoit ces parties. Le premier modèle qui correspond l'emporte.
 */
export const EN_PATTERNS: [RegExp, string | ((...parts: string[]) => string)][] = [
  [
    /^Connexion réussie : Home Assistant (.*), (\d+) appareil\(s\) et capteur\(s\)\.$/,
    (version, n) => `Connected: Home Assistant${version ? ` ${version}` : ''}, ${n} device(s) and sensor(s).`,
  ],
  [
    /^Connexion réussie : (.+?)(?:, flux secondaire (.+?))?( \(pas de flux secondaire : la vidéo complète sera aussi utilisée pour les miniatures\))?\.$/,
    (main, sub, none) =>
      `Connected: ${resolution(main)}${sub ? `, secondary stream ${resolution(sub)}` : ''}${none ? ' (no secondary stream: the full video will also be used for thumbnails)' : ''}.`,
  ],
  [/^Lecture du flux impossible(?: \(([\s\S]*)\))?\.$/, (detail) => `Could not read the stream${detail ? ` (${detail})` : ''}.`],
  [/^La caméra a répondu « (.*) » à cette adresse\.$/, 'The camera responded “$1” at this address.'],
  [/^Le serveur distant a répondu (\d+)\.$/, 'The remote server responded $1.'],
  [/^Home Assistant a répondu (\d+)\.$/, 'Home Assistant responded $1.'],
  [/^Seerr a refusé : ([\s\S]*)$/, 'Seerr refused: $1'],
  [/^Seerr a répondu : erreur (\d+)\.$/, 'Seerr responded: error $1.'],
  [/^Fichier trop volumineux \(max (\d+) Mo\)\.$/, 'File too large (max $1 MB).'],
  [/^(-?\d+(?:[.,]\d+)?) %$/, '$1%'],
];
